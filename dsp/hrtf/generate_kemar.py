#!/usr/bin/env python3
"""Reproduce KemarDiffuseData.h from MIT's original diffuse.zip, stdlib only.

Usage: python dsp/hrtf/generate_kemar.py --archive path/to/diffuse.zip
If --archive is omitted, download the exact pinned archive into memory. No
extraction, third-party package, training, or external service is involved.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import struct
import urllib.request
import wave
import zipfile

URL = "https://sound.media.mit.edu/resources/KEMAR/diffuse.zip"
SHA256 = "a48e73137390626ef1e45d1de6a4d98530c6aa570e71b40f7c4442241ed5fa22"
COUNTS = [56, 60, 72, 72, 72, 72, 72, 60, 56, 45, 36, 24, 12, 1]


def generate(blob, directory):
    digest = hashlib.sha256(blob).hexdigest()
    if digest != SHA256:
        raise ValueError(f"Archive SHA256 mismatch: {digest}")
    records, rings, manifests = [], [], []
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        for elevation, count in zip(range(-40, 91, 10), COUNTS):
            ring = []
            for name in archive.namelist():
                match = re.fullmatch(r"elev(-?\d+)/H(-?\d+)e(\d+)a\.wav", name)
                if not match or int(match[1]) != elevation:
                    continue
                if int(match[2]) != elevation:
                    raise ValueError(f"Mismatching filename elevation: {name}")
                azimuth = int(match[3])
                with wave.open(io.BytesIO(archive.read(name)), "rb") as wav:
                    if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(),
                            wav.getnframes(), wav.getcomptype()) != (2, 2, 44100, 128, "NONE"):
                        raise ValueError(f"Unexpected WAV format: {name}")
                    samples = struct.unpack("<256h", wav.readframes(128))
                ring.append((azimuth, samples, name))
            ring.sort()
            expected_half = count // 2 + 1
            if len(ring) != expected_half:
                raise ValueError(f"Elevation {elevation}: wrong half-ring count")
            first = len(records)
            for index, (azimuth, samples, name) in enumerate(ring):
                # Filenames round the equal-angle grid. Use 360/count in DSP,
                # not rounded filenames (e.g. the 56-point +/-40 degree rings).
                expected = int(index * 360.0 / count + 0.5) if count > 1 else 0
                if azimuth != expected:
                    raise ValueError(f"Unexpected azimuth grid: {name}, expected {expected}")
                records.append((samples[0::2], samples[1::2]))
                manifests.append({"file": name, "elevation_deg": elevation,
                                  "azimuth_clockwise_deg": index * 360.0 / count})
            rings.append((elevation, first, count, expected_half))
    if len(records) != 368 or sum(COUNTS) != 710:
        raise ValueError("Unexpected dataset size")
    lines = ["// Generated by generate_kemar.py; do not hand edit.",
             "// MIT Media Laboratory (1994); Bill Gardner and Keith Martin.",
             "// Source, usage permission, attribution and processing: NOTICE.md.",
             "#pragma once", "#include <cstdint>", "",
             "namespace dreamdsp::dsp::kemar_diffuse {",
             "inline constexpr int kSampleRate = 44100;",
             "inline constexpr int kTaps = 128;",
             "inline constexpr int kMeasurements = 368;",
             "inline constexpr int kRingCount = 14;",
             "struct Ring { int elevation, first, count, halfCount; };",
             "inline constexpr Ring kRings[kRingCount] = {"]
    lines += ["    {%d, %d, %d, %d}," % ring for ring in rings]
    lines += ["};", "// Stored half-space: clockwise azimuth, ears L/R, unmodified PCM16.",
              "inline constexpr int16_t kHrir[kMeasurements][2][kTaps] = {"]
    for ears in records:
        lines.append("    {")
        for ear in ears:
            lines.append("        {")
            for start in range(0, 128, 16):
                lines.append("            " + ", ".join(map(str, ear[start:start + 16])) + ",")
            lines.append("        },")
        lines.append("    },")
    lines += ["};", "} // namespace dreamdsp::dsp::kemar_diffuse", ""]
    directory.joinpath("KemarDiffuseData.h").write_text("\n".join(lines), encoding="utf-8")
    manifest = {"source": URL, "source_sha256": SHA256, "sample_rate": 44100,
                "taps_per_ear": 128, "stored_measurements": 368,
                "full_sphere_directions": 710, "elevation_range_deg": [-40, 90],
                "position_radius_m": 1.4, "quantisation": "original signed PCM16 / 32768",
                "processing": "Lossless WAV decode and deinterleave only; no normalisation.",
                "azimuth": "Clockwise from front; 90 degrees is listener's right.",
                "mirror": "For unrecorded left hemisphere, mirror azimuth and swap ears.",
                "measurements": manifests}
    directory.joinpath("KemarDiffuseData.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {len(records)} HRIR pairs, {sum(COUNTS)} mirrored directions; SHA256 {digest}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path)
    args = parser.parse_args()
    source = args.archive.read_bytes() if args.archive else urllib.request.urlopen(URL, timeout=60).read()
    generate(source, Path(__file__).resolve().parent)
